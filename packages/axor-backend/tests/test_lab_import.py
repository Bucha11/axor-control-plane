async def test_broken_manifests_and_pins_are_refused(
    client: httpx.AsyncClient, cp_deploy: dict[str, object],
) -> None:
    bad = copy.deepcopy(cp_deploy)
    bad["tool_manifests"] = [{"id": "x"}]
    bad["regressions"] = [{"trace_id": "", "expected_verdict": "MAYBE"}]
    r = await client.post("/v1/lab/deploy", json=bad)
    assert r.status_code == 422
    reasons = "\n".join(r.json()["detail"]["reasons"])
    assert "tool_manifests[0]" in reasons
    assert "expected_verdict" in reasons
    # nothing was stored or pinned
    assert (await client.get("/v1/lab/deploys")).json() == []
    assert (await client.get("/v1/pins")).json()["total"] == 0


async def test_deploy_requires_operate_scope(
    secured: httpx.AsyncClient, cp_deploy: dict[str, object],
) -> None:
    # anonymous → 401
    assert (await secured.post("/v1/lab/deploy", json=cp_deploy)).status_code == 401
    # a read-only key may list but not deploy
    read_key = (await secured.post(
        "/v1/keys", json={"scopes": ["read"]}, headers=_bearer(TOKEN),
    )).json()["secret"]
    denied = await secured.post("/v1/lab/deploy", json=cp_deploy,
                                headers=_bearer(read_key))
    assert denied.status_code == 403
    assert denied.json()["need"] == "operate"
    assert (await secured.get("/v1/lab/deploys",
                              headers=_bearer(read_key))).status_code == 200
    # an operate key deploys
    op_key = (await secured.post(
        "/v1/keys", json={"scopes": ["operate"]}, headers=_bearer(TOKEN),
    )).json()["secret"]
    assert (await secured.post("/v1/lab/deploy", json=cp_deploy,
                               headers=_bearer(op_key))).status_code == 200


async def test_lab_package_readable_with_read_scope(secured: httpx.AsyncClient) -> None:
    """The CP → Lab side is a read: a read key may export, anonymous may not."""
    await secured.post("/v1/demo/seed-adapter-runs", headers=_bearer(TOKEN))
    assert (await secured.get("/v1/runs/ex_block/lab-package")).status_code == 401
    read_key = (await secured.post(
        "/v1/keys", json={"scopes": ["read"]}, headers=_bearer(TOKEN),
    )).json()["secret"]
    assert (await secured.get("/v1/runs/ex_block/lab-package",
                              headers=_bearer(read_key))).status_code == 200
