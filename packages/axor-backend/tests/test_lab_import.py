def _bearer(token: str) -> dict[str, str]:
    return {"Authorization": f"Bearer {token}"}


async def test_valid_deploy_creates_pins_and_record(
    client: httpx.AsyncClient, cp_deploy: dict[str, object],
) -> None:
    r = await client.post("/v1/lab/deploy", json=cp_deploy)
    assert r.status_code == 200, r.text
    body = r.json()
    assert body["policy_stored"] is True
    assert body["pins_created"] == 1
    assert body["already_deployed"] is False
    package_id = body["package_id"]

    # the pin is in the corpus, source-labelled with the package
    pins = (await client.get("/v1/pins")).json()
    lab_pins = [p for p in pins["pins"] if p["label"] == f"lab:{package_id}"]
    assert len(lab_pins) == 1
    assert lab_pins[0]["side"] == "must_block"
    assert lab_pins[0]["run_id"].startswith("lab:")

    # and the package record is listed
    deploys = (await client.get("/v1/lab/deploys")).json()
    assert [d["package_id"] for d in deploys] == [package_id]
    assert deploys[0]["pins_created"] == 1
    assert deploys[0]["kernel"] == KERNEL
    assert deploys[0]["source"]["condition_id"] == "governed"


async def test_reupload_is_idempotent(
    client: httpx.AsyncClient, cp_deploy: dict[str, object],
) -> None:
    first = (await client.post("/v1/lab/deploy", json=cp_deploy)).json()
    second = (await client.post("/v1/lab/deploy", json=cp_deploy)).json()
    assert second["package_id"] == first["package_id"]
    assert second["already_deployed"] is True
    deploys = (await client.get("/v1/lab/deploys")).json()
    assert len(deploys) == 1
    pins = (await client.get("/v1/pins")).json()
    assert pins["total"] == 1


