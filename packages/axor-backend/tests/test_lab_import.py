async def test_deploy_requires_operate_scope(
    secured: httpx.AsyncClient, cp_deploy: dict[str, object],
) -> None:
    # anonymous → 401
    assert (await secured.post("/v1/lab/deploy", json=cp_deploy)).status_code == 401
    # a read-only key may list but not deploy
    read_key = (await secured.post(
        "/v1/keys", json={"scopes": ["read"]}, headers=_bearer(TOKEN),
    )).json()["secret"]
    denied = await secured.post("/v1/lab/deploy", json=cp_deploy,
                                headers=_bearer(read_key))
    assert denied.status_code == 403
    assert denied.json()["need"] == "operate"
    assert (await secured.get("/v1/lab/deploys",
                              headers=_bearer(read_key))).status_code == 200
    # an operate key deploys
    op_key = (await secured.post(
        "/v1/keys", json={"scopes": ["operate"]}, headers=_bearer(TOKEN),
    )).json()["secret"]
    assert (await secured.post("/v1/lab/deploy", json=cp_deploy,
                               headers=_bearer(op_key))).status_code == 200


